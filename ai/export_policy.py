"""Export the PPO actor network to a small JS file so game.html can run it in the browser.

SB3's default MlpPolicy actor is Linear(5,64) -> Tanh -> Linear(64,64) -> Tanh -> Linear(64,3).
The weights are written as `window.PONG_AI_WEIGHTS = {...}` so it loads via a plain
<script> tag (fetch() of a local JSON file is blocked when opening game.html from disk).
Usage:  python export_policy.py
"""
import argparse
import json

import torch.nn as nn
from stable_baselines3 import PPO

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="models/ppo_pong_agent.zip")
    parser.add_argument("--out", default="models/ppo_pong_agent.js")
    args = parser.parse_args()

    policy = PPO.load(args.model).policy
    linears = [m for m in policy.mlp_extractor.policy_net if isinstance(m, nn.Linear)] + [policy.action_net]
    layers = [
        {"weights": [[round(w, 6) for w in row] for row in layer.weight.tolist()],
         "bias": [round(b, 6) for b in layer.bias.tolist()]}
        for layer in linears
    ]
    with open(args.out, "w") as f:
        f.write("// Generated by ai/export_policy.py from the trained PPO agent. Do not edit.\n")
        f.write("window.PONG_AI_WEIGHTS = ")
        json.dump({"activation": "tanh", "layers": layers}, f, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {args.out} ({len(layers)} layers)")
