"""Export each level's PPO actor network to a small JS file so game.html can run it in the browser.

SB3's default MlpPolicy actor is Linear(6,64) -> Tanh -> Linear(64,64) -> Tanh -> Linear(64,3).
Each file adds `window.PONG_AI_LEVELS[level] = {...}` so it loads via a plain <script> tag
(fetch() of a local JSON file is blocked when opening game.html from disk).
Usage:  python export_policy.py            # every level in levels.py that has a trained model
        python export_policy.py medium     # just one
"""
import argparse
import json
import os

from stable_baselines3 import PPO

from levels import LEVELS
from opponents import NumpyPolicy


def export(level):
    config = LEVELS[level]
    policy = NumpyPolicy.from_sb3(PPO.load(config["model"], device="cpu").policy)
    layers = [
        {"weights": [[round(w, 6) for w in row] for row in weights.tolist()],
         "bias": [round(b, 6) for b in bias.tolist()]}
        for weights, bias in policy.layers
    ]
    out = config["model"].removesuffix(".zip") + ".js"
    with open(out, "w") as f:
        f.write("// Generated by ai/export_policy.py from the trained PPO agent. Do not edit.\n")
        f.write("window.PONG_AI_LEVELS = window.PONG_AI_LEVELS || {};\n")
        f.write(f"window.PONG_AI_LEVELS[{json.dumps(level)}] = ")
        json.dump({"ballSpeed": config["ball_speed"], "activation": "tanh", "layers": layers}, f,
                  separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {out} ({len(layers)} layers, ball speed {config['ball_speed']}x)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("levels", nargs="*", default=[l for l, c in LEVELS.items() if os.path.exists(c["model"])])
    args = parser.parse_args()
    for level in args.levels:
        export(level)
